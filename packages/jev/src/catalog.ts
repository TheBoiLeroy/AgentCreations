// Metadata describes requirements, not installed capabilities or a completed test.
export const catalog = entries.map((tool) => {
  const external = getSkillSource(tool.id);
  return {
    ...tool,
    tier: external ? "shared" : "built-in",
    source: external ? "imported_skill" : "builtin",
    source_url: external ? `https://skills.sh/${external.repository}/${external.skill}` : null,
    version: "1",
    owner_id: null,
    visibility: "public",
    inputs: questions[tool.id] || [],
    permissions: {
      sends_email: tool.id === "send-email",
      reads_files: ["read-files", "extract-documents", "analyze-data"].includes(tool.id) || !!external,
      network: !!tool.connection || tool.id === "web-search" || tool.id === "skill-webapp-testing",
      posts_publicly: false,
    },
    requires_model_run: true,
    supported_runtimes: ["worker"],
    tested: false,
  } satisfies SkillRecord;
});
