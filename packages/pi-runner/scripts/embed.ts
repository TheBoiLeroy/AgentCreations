// Embeds the template sources as strings so exporters stay pure and browser-safe.
// Run after editing templates: corepack pnpm templates
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const templateFiles = {
  workerSource: "worker.ts",
  extensionSource: "extension.ts",
  calcSource: "calc.ts",
  extractSource: "extract.ts",
} as const;
export function renderTemplates(): string {
  const root = new URL("../templates/", import.meta.url);
  const body = Object.entries(templateFiles)
    .map(
      ([name, file]) =>
        `export const ${name} = ${JSON.stringify(readFileSync(new URL(file, root), "utf8"))};`,
    )
    .join("\n");
  return `// Generated by packages/pi-runner/scripts/embed.ts from templates/. Do not edit.\n${body}\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  writeFileSync(new URL("../src/templates.ts", import.meta.url), renderTemplates());
